/**
 * Ключ логина для поиска и проверки занятости: «Аня», «аня» и «АНЯ» — один пользователь.
 * SQLite COLLATE NOCASE сравнивает без регистра только латиницу, поэтому ключ считаем сами.
 * NFC — чтобы «й», набранная одной или двумя кодовыми точками, тоже совпадала.
 * Отображается по-прежнему users.login — в том написании, как ввели при регистрации.
 */
export function loginKey(login: string): string {
  return login.normalize("NFC").trim().toLocaleLowerCase("ru");
}
